-- Filtro de tempo de evento valido, aplicado no WHERE de cada agregacao.
--
-- O Jetstream entrega, de vez em quando, um `createdAt` que nao converte
-- (nulo, vazio, formato estranho). Sem este filtro o Flink derruba o job com
-- "RowTime field should not be null". Descartar e o comportamento certo: post
-- sem tempo de evento nao entra em janela nenhuma.
--
-- Fica como fragmento e nao como VIEW porque, no Flink 1.20, uma view por
-- cima da tabela com watermark quebra o planner ("belongs to a different
-- planner"). O filtro entra direto em cada INSERT.
